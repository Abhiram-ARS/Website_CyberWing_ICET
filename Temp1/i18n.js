const languageStorageKey = 'cyberwing-language';
let currentLanguage = localStorage.getItem(languageStorageKey) || 'en';

function translateText(value) {
  const key = value.trim().replace(/\s+/g, ' ');
  return translations[currentLanguage][key] || value;
}

function applyLanguage(language) {
  currentLanguage = translations[language] ? language : 'en';
  localStorage.setItem(languageStorageKey, currentLanguage);
  document.documentElement.lang = currentLanguage;
  document.title = translateText('CyberWing | Intelligent Defense for the Digital Age');

  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    const normalizedKey = key.trim().replace(/\s+/g, ' ');
    const translated = translations[currentLanguage][normalizedKey]
      || (currentLanguage === 'en' ? normalizedKey : key);

    if (currentLanguage === 'en' || translations[currentLanguage][normalizedKey]) {
      element.textContent = translated;
    }
  });

  document.querySelectorAll('body *').forEach(element => {
    if (element.children.length > 0 || element.hasAttribute('data-i18n')) return;

    const original = element.textContent.trim();
    const translated = translateText(original);

    if (original && translated !== original) {
      element.textContent = translated;
      element.setAttribute('data-i18n', original);
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
    element.placeholder = translateText(
      element.getAttribute('data-i18n-placeholder')
    );
  });

  document.querySelectorAll('[data-i18n-title]').forEach(element => {
    element.title = translateText(
      element.getAttribute('data-i18n-title')
    );
  });

  document.querySelectorAll('[data-i18n-aria-label]').forEach(element => {
    element.setAttribute(
      'aria-label',
      translateText(element.getAttribute('data-i18n-aria-label'))
    );
  });

  document.querySelectorAll('[data-language]').forEach(button => {
    button.classList.toggle(
      'active',
      button.getAttribute('data-language') === currentLanguage
    );

    button.setAttribute(
      'aria-pressed',
      button.getAttribute('data-language') === currentLanguage
    );
  });
}

window.cyberwingI18n = {
  get language() {
    return currentLanguage;
  },
  translate: translateText,
  apply: applyLanguage
};

document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('[data-language]').forEach(button => {
    button.addEventListener('click', () => {
      applyLanguage(button.getAttribute('data-language'));
    });
  });

  applyLanguage(currentLanguage);
});

